export type VoicePack = {
  select: string;
  ult: string;
  death: string;
  win: string;
  kill: string;
  casts: string[];
};

export type KitPatch = {
  difficulty: Difficulty;
  band: RoleBand;
  kind: PassiveKind;
  stack: string;
  bio: string;
  personality: string;
  style: string;
  hpRegen: number;
  manaRegen: number;
  aspd: number;
  mr: number;
  passive: Passive;
  voice: VoicePack;
  blurbs?: Partial<Record<"Q" | "W" | "E" | "R", string>>;
};

function V(select: string, ult: string, death: string, win: string, kill: string, ...casts: string[]): VoicePack {
  return { select, ult, death, win, kill, casts };
}

function K(
  difficulty: Difficulty,
  band: RoleBand,
  kind: PassiveKind,
  stack: string,
  pname: string,
  pblurb: string,
  bio: string,
  personality: string,
  style: string,
  hpRegen: number,
  manaRegen: number,
  aspd: number,
  mr: number,
  voice: VoicePack,
  blurbs?: KitPatch["blurbs"],
): KitPatch {
  return {
    difficulty,
    band,
    kind,
    stack,
    bio,
    personality,
    style,
    hpRegen,
    manaRegen,
    aspd,
    mr,
    passive: { name: pname, blurb: pblurb },
    voice,
    blurbs,
  };
}

