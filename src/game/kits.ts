export function kitPatch(id: string): KitPatch {
  return KITS[id] ?? FALLBACK;
}

export function diffStars(n: Difficulty): string {
  return n === 1 ? "★☆☆" : n === 2 ? "★★☆" : "★★★";
}

export function diffLabel(n: Difficulty): string {
  return n === 1 ? "Easy" : n === 2 ? "Medium" : "Hard";
}

export function bandLabel(band: RoleBand): string {
  if (band === "tank") return "Tank";
  if (band === "fighter") return "Fighter";
  if (band === "assassin") return "Assassin";
  if (band === "mage") return "Mage";
  if (band === "marksman") return "Marksman";
  if (band === "support") return "Support";
  return "Controller";
}

export function sealHero(h: HeroDef): HeroDef {
  const k = kitPatch(h.id);
  const abilities = h.abilities.map((ab) => ({
    ...ab,
    blurb: ab.mech ? ab.blurb : (k.blurbs?.[ab.key] ?? ab.blurb),
  }));
  const voice = h.wing === "maga" ? { ...k.voice, death: MAGA_DEATH } : k.voice;
  return {
    ...h,
    abilities,
    passive: k.passive,
    difficulty: k.difficulty,
    bio: k.bio,
    personality: k.personality,
    style: k.style,
    hpRegen: k.hpRegen,
    manaRegen: k.manaRegen,
    aspd: k.aspd,
    mr: k.mr,
    kind: k.kind,
    band: k.band,
    stack: k.stack,
    voice,
  };
}
